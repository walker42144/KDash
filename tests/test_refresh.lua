return function(T)
 local App=require('core.app')
 local Scheduler=require('core.scheduler')
 local function app()
  local calls={}
  local a=App.new({config={data={ui={refresh_minutes=5,direct_exit=true}}},clock={now=function() return 1000 end}})
  a.refresh_anchor=1000;a.next_screen_at=1300;a.last_render_at=1000;a.page={id='home'}
  a.renderer={render_dirty=function(_,ids) calls[#calls+1]=ids end}
  return a,calls
 end
 T.test('automatic updates share baseline and merge late results at next slot',function()
  local a,calls=app()
  a.dirty.clock=true;T.falsy(a:render_pending(1299));T.eq(#calls,0)
  a.dirty.dida=true;T.truthy(a:render_pending(1300));T.eq(#calls[1],2)
  a.dirty.weather=true;T.falsy(a:render_pending(1360));T.falsy(a:render_pending(1420))
  T.truthy(a:render_pending(1600));T.eq(#calls,2);T.eq(calls[2][1],'weather')
 end)
 T.test('empty display slots advance without refresh; manual refresh keeps baseline',function()
  local a,calls=app()
  T.falsy(a:render_pending(1300));T.eq(a.next_screen_at,1600)
  a.dirty.weather=true;T.falsy(a:render_pending(1301))
  a.force_render=true;T.truthy(a:render_pending(1370));T.eq(a.next_screen_at,1600)
  a.dirty.clock=true;T.truthy(a:render_pending(1600));T.eq(a.next_screen_at,1900)
 end)
 T.test('scheduler interval uses shared anchor after async completion',function()
  local s=Scheduler.new({coalesce_window=3})
  s:add('a',{interval=900,anchor=1000,align='interval',no_coalesce=true,now=1000})
  s:success('a',1067);T.eq(s:get('a').next_due,1900)
  s:add('b',{interval=300,anchor=1000,align='interval',no_coalesce=true,now=1000,on_start=false})
  s:add('c',{interval=10,now=1298})
  local due=s:tick(1298);T.eq(#due,1);T.eq(due[1],'c')
  T.eq(s:get('b').next_due,1300)
 end)
 T.test('network retries stay on shared display grid',function()
  local s=Scheduler.new();s:add('a',{interval=900,anchor=1000,batch_interval=300,now=1000})
  s:failure('a','offline',1087);T.eq((s:get('a').next_due-1000)%300,0)
 end)
 T.test('date-only countdown checks local midnight instead of every minute',function()
  local m=require('modules.countdown.init')
  local ctx={config={data={ui={refresh_minutes=5}},module=function() return {events={{date='2030-01-01'}}} end}}
  local p=m.refresh_policy(ctx);T.eq(p.align,'day');T.eq(p.interval,86400);T.eq(p.on_start,false)
 end)
 T.test('clock respects configured five-minute cadence',function()
  local m=require('modules.clock.init');local p=m.refresh_policy({config={data={ui={refresh_minutes=5}}}})
  T.eq(p.interval,300);T.eq(p.align,'interval');T.truthy(p.no_coalesce);T.eq(p.on_start,false)
 end)
 T.test('manual async completion bypasses waiting without moving the anchor',function()
  local a,calls=app();a.scheduler=Scheduler.new();a.scheduler:add('weather',{now=1000})
  a.manual_refresh.weather=true;a:finish_refresh('weather',true)
  T.truthy(a:render_pending(1100));T.eq(#calls,1);T.eq(a.next_screen_at,1300)
  a:handle_action({action='exit_request'});T.truthy(a.stop)
 end)
 T.test('application jobs use one baseline and preserve whole-period alignment',function()
  local a=app();a.scheduler=Scheduler.new()
  a.registry={get=function(_,id) return {inst={__ctx={},refresh_policy=function() return {interval=id=='dida' and 900 or 1800} end}} end}
  a:add_job('dida');a:add_job('weather')
  a.scheduler:success('dida',1080);a.scheduler:success('weather',1130)
  T.eq(a.scheduler:get('dida').next_due,1900);T.eq(a.scheduler:get('weather').next_due,2800)
  T.truthy(a.scheduler:get('dida').policy.no_coalesce)
 end)
 T.test('zero periodic full refresh survives configuration validation',function()
  local Config=require('core.config');local c=Config.new({});c.data={ui={refresh_minutes=5},power={full_refresh_every=0}}
  c:validate();T.eq(c.data.ui.refresh_minutes,5);T.eq(c.data.power.full_refresh_every,0)
  c.data.power.full_refresh_every=1000;c:validate();T.eq(c.data.power.full_refresh_every,1000)
 end)

end
