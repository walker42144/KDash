return function(T)
 local meta=require('services.task_metadata');local json=require('core.json')
 T.test('task time formats range, single instant, midnight, UTC offsets and all-day correctly',function()
  T.eq(meta.time_label({source_start='2026-11-12T02:05:00+0800',source_due='2026-11-12T03:05:00+0800',is_all_day=false},480),'02:05-03:05')
  T.eq(meta.time_label({source_start='2026-11-12T02:05:00+0800',source_due='2026-11-12T02:05:00+0800',is_all_day=false},480),'02:05')
  T.eq(meta.time_label({source_due='2026-11-11T16:00:00Z',is_all_day=false},480),'00:00')
  T.eq(meta.time_label({source_due='2026-11-12T00:00:00+0800',is_all_day=true},480),nil)
  T.eq(meta.time_label({source_due='2026-11-12T00:00:00+0800'},480),nil)
  T.eq(meta.time_label({startDate='2026-11-12T23:30:00+0800',dueDate='2026-11-13T00:30:00+0800',isAllDay=false},480),'23:30-00:30')
  T.eq(meta.time_label({startDate='2026-11-12',isAllDay=false},480),nil)
 end)
 T.test('metadata order is time then deduplicated exact tags without hashtags',function()
  local badges=meta.badges({source_due='2026-11-12T10:00:00+0800',is_all_day=false,tags={'学习','数学','学习'}})
  T.eq(#badges,3);T.eq(badges[1].kind,'time');T.eq(badges[2].text,'学习');T.eq(badges[3].text,'数学')
 end)
 T.test('long title and wrapped metadata are measured inside reserved priority bounds',function()
  local UI=require('ui.components');local typo=require('ui.typography').new({measure=function(s,size) return #require('core.util').utf8_codepoints(s)*size end})
  local ui=UI.new({theme=require('ui.theme').new({}),typo=typo})
  local width=960-ui:priority_reserve(5);local layout=ui:task_layout({w=width},string.rep('长任务名称',100),nil,{size=32,badges=meta.badges({source_due='2026-11-12T10:00:00+0800',is_all_day=false,tags={'学习','数学','很长很长的复习标签'}})})
  T.truthy(typo:measure(layout.title,32)<=layout.title_w)
  for _,b in ipairs(layout.badges) do T.truthy(b.x+b.w<=width);T.truthy(b.y+39<=layout.h) end
 end)
 T.test('UTF-8 prefix and measured ellipsis never cut a character or exceed budget',function()
  T.eq(require('core.util').utf8_prefix('学习学习',4),'学...')
  local typo=require('ui.typography').new({measure=function(s) return #require('core.util').utf8_codepoints(s)*9 end})
  local value=typo:fit('学习学习学习',40,22);T.truthy(typo:measure(value,22)<=40)
 end)
 T.test('deeply nested remote JSON fails before recursive stack exhaustion',function()
  T.falsy(pcall(json.decode,string.rep('[',70)..'0'..string.rep(']',70)))
  T.truthy(pcall(json.decode,string.rep('[',20)..'0'..string.rep(']',20)))
 end)
 T.test('HTTP bounds concurrent jobs and cancellation cannot schedule more jobs',function()
  local files={};local storage={write=function(_,p,v) files[p]=v;return true end,read=function(_,p) return files[p] end,exists=function(_,p) return files[p]~=nil end,remove=function(_,p) files[p]=nil end,chmod=function() end}
  local spawns=0;local h=require('services.http').new({storage=storage,runner={spawn_script=function() spawns=spawns+1 end},dir='/fake',now=function() return 1 end})
  for i=1,4 do h:request({url='https://example.invalid'},function() end) end
  local result;h:request({url='https://example.invalid'},function(r) result=r end);T.eq(result.error,'request queue full');T.eq(spawns,4)
  h:cancel_all();h:request({url='https://example.invalid'},function(r) result=r end);T.eq(result.error,'cancelled');T.eq(spawns,4)
 end)
 T.test('HTTP oversized body is rejected before decoding or exposing payload',function()
  local files={};local result
  local storage={write=function(_,p,v) files[p]=v;return true end,read=function(_,p) return files[p] end,exists=function(_,p) return files[p]~=nil end,remove=function(_,p) files[p]=nil end,chmod=function() end}
  local h=require('services.http').new({storage=storage,runner={spawn_script=function() end},dir='/fake',now=function() return 1 end})
  h:request({url='https://example.invalid',max_bytes=8},function(r) result=r end)
  local p='/fake/http-1-1';files[p..'.done']='done';files[p..'.rc']='0';files[p..'.status']='200';files[p..'.out']=string.rep('x',20)
  h:poll();T.falsy(result.ok);T.eq(result.body,'');T.eq(result.error,'response exceeds size limit')
 end)
 T.test('API view and cache roundtrip preserve timed-task metadata',function()
  local v=require('services.api.dida').build_view({{id='p',name='Study'}},{p={tasks={{id='t',projectId='p',title='Review',startDate='2026-11-12T02:05:00+0800',dueDate='2026-11-12T03:05:00+0800',isAllDay=false,tags={'学习'}}}}},require('core.timeutil').parse_iso8601('2026-11-12T12:00:00+0800'),480,{})
  local restored=json.decode(json.encode(v));T.eq(meta.time_label(restored.today[1],480),'02:05-03:05');T.eq(meta.badges(restored.today[1])[2].text,'学习')
 end)

 T.test('accepted task hierarchy remains within cache JSON decoder depth limit',function()
  local tasks={};for i=1,24 do tasks[i]={id=tostring(i),projectId='p',title='t',parentId=i>1 and tostring(i-1) or nil,dueDate='2026-11-12',isAllDay=true} end
  local api=require('services.api.dida');local v=api.build_view({{id='p'}},{p={tasks=tasks}},require('core.timeutil').parse_iso8601('2026-11-12T12:00:00+0800'),480,{})
  T.truthy(json.decode(json.encode({data={view=v}})))
  for i=25,30 do tasks[i]={id=tostring(i),projectId='p',title='t',parentId=tostring(i-1)} end
  T.falsy(pcall(api.build_view,{{id='p'}},{p={tasks=tasks}},0,480,{}))
 end)

 T.test('start-only timed tasks remain eligible for today and display one time',function()
  local api=require('services.api.dida');local v=api.build_view({{id='p'}},{p={tasks={{id='single',projectId='p',title='Task',startDate='2026-11-12T02:05:00+0800',isAllDay=false}}}},require('core.timeutil').parse_iso8601('2026-11-12T12:00:00+0800'),480,{})
  T.eq(#v.today,1);T.eq(meta.time_label(v.today[1],480),'02:05')
 end)

