return function(T)
    local Scheduler = require("core.scheduler")

    T.test("scheduler adds due job and succeeds", function()
        local s = Scheduler.new({ coalesce_window = 2 })
        s:add("a", { interval = 60, now = 1000, on_start = true })
        local due = s:tick(1000)
        T.eq(#due, 1)
        T.eq(due[1], "a")
        s:success("a", 1000)
        T.eq(s:get("a").next_due, 1060)
    end)

    T.test("scheduler align minute", function()
        local s = Scheduler.new()
        s:add("a", { interval = 60, now = 1005, on_start = false, align = "minute" })
        T.eq(s:get("a").next_due, 1020)
        T.eq(#s:tick(1019), 0)
        T.eq(#s:tick(1020), 1)
    end)

    T.test("scheduler coalesces near-due jobs", function()
        local s = Scheduler.new({ coalesce_window = 5 })
        s:add("a", { interval = 60, now = 1000 })
        s:add("b", { interval = 60, now = 1003 })
        local due = s:tick(1000)
        T.eq(#due, 2)
    end)

    T.test("scheduler backoff on failure", function()
        local s = Scheduler.new()
        s:add("a", { interval = 60, now = 1000, max_backoff = 3600 })
        s:tick(1000)
        s:failure("a", "boom", 1000)
        T.eq(s:get("a").failures, 1)
        T.eq(s:get("a").next_due, 1120)
        T.eq(#s:tick(1119), 0)
        T.eq(#s:tick(1120), 1)
    end)

    T.test("scheduler force and remove", function()
        local s = Scheduler.new()
        s:add("a", { interval = 3600, now = 1000, on_start = false })
        s:force("a", 1000)
        T.eq(#s:tick(1000), 1)
        s:success("a", 1000)
        s:remove("a")
        T.eq(s:get("a"), nil)
    end)
end
