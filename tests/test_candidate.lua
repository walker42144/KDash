return function(T)
 local Touch=require('platform.kindle.touch')
 local function e(t,c,v) return {type=t,code=c,value=v} end
 local syn=e(0,0,0)
 T.test('tracking tap persists across separate evdev reads',function()
  local t=Touch.new({clock_ms=function() return 0 end})
  t:feed({e(3,57,1),e(3,53,100),e(3,54,200),syn})
  local out=t:feed({e(3,57,-1),syn})
  T.eq(#out,1); T.eq(out[1].x,100); T.eq(out[1].y,200)
 end)
 T.test('protocol A contact and empty release frame',function()
  local t=Touch.new({clock_ms=function() return 0 end})
  t:feed({e(3,53,100),e(3,54,200),e(0,2,0),syn})
  local out=t:feed({e(0,2,0),syn})
  T.eq(#out,1); T.eq(out[1].type,'tap')
 end)
 T.test('legacy single touch axes and button release',function()
  local t=Touch.new({clock_ms=function() return 0 end}); t.xcode,t.ycode=0,1
  t:feed({e(3,0,100),e(3,1,200),e(1,330,1),syn})
  T.eq(#t:feed({e(1,330,0),syn}),1)
 end)
 T.test('new contact cannot reuse stale coordinates',function()
  local t=Touch.new({clock_ms=function() return 0 end})
  t:feed({e(3,57,1),e(3,53,100),e(3,54,200),syn})
  t:feed({e(3,57,-1),syn})
  t:feed({e(3,57,2),e(3,53,900),syn})
  T.eq(#t:feed({e(3,57,-1),syn}),0)
 end)
 T.test('dropped frame cannot generate an exit tap',function()
  local t=Touch.new({clock_ms=function() return 0 end})
  t:feed({e(3,57,1),e(3,53,100),e(3,54,200),syn})
  T.eq(#t:feed({e(0,3,0),e(3,57,-1),syn}),0)
 end)
 T.test('protocol A multiple contacts cancel tap',function()
  local t=Touch.new({clock_ms=function() return 0 end})
  t:feed({e(3,53,10),e(3,54,20),e(0,2,0),e(3,53,30),e(3,54,40),e(0,2,0),syn})
  T.eq(#t:feed({e(0,2,0),syn}),0)
 end)
 T.test('axis range transform and bounds',function()
  local t=Touch.new({axes={xmin=10,xmax=1010,ymin=20,ymax=2020},swap_xy=true,invert_x=true})
  local x,y=t:map(1010,20); T.eq(x,1071); T.eq(y,1447)
  T.eq(t:map(-1,20),nil)
 end)
 T.test('impossible target date rejected',function()
  T.eq(require('core.timeutil').parse_date('2026-02-30'),nil)
  T.eq(require('core.timeutil').parse_date('2024-02-29'),2024)
 end)
 T.test('one tap exit setting stops application directly',function()
  local app=setmetatable({config={data={ui={direct_exit=true}}}},require('core.app'))
  app:handle_action({action='exit_request'}); T.truthy(app.stop)
 end)
 T.test('failed final refresh marks display unavailable',function()
  local d=require('platform.kindle.display_fbink').new({fbink='fbink',runner={run=function() return 1,'refresh failure' end}})
  d:add_dirty(0,0,100,100); T.falsy(d:flush({full=true})); T.falsy(d.available)
 end)
end
